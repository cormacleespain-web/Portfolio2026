/**
 * Converts "Cormac Lee" in the Ephesis Google Font into SVG path data.
 * Run: node scripts/generate-name-svg.mjs
 * Output: components/ui/hero-name-paths.ts
 */

import opentype from "opentype.js";
import { writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const FONT_URL =
  "https://fonts.gstatic.com/s/ephesis/v11/uU9PCBUS8IerL2VG7xM.ttf";
const TEXT = "Cormac Lee";
const FONT_SIZE = 200;
const X_OFFSET = 0;
const Y_OFFSET = FONT_SIZE;

async function main() {
  const res = await fetch(FONT_URL);
  const buffer = await res.arrayBuffer();
  const font = opentype.parse(buffer);

  const path = font.getPath(TEXT, X_OFFSET, Y_OFFSET, FONT_SIZE);
  const d = path.toPathData(2);
  const bbox = path.getBoundingBox();

  const padding = 4;
  const x1 = Math.floor(bbox.x1) - padding;
  const y1 = Math.floor(bbox.y1) - padding;
  const width = Math.ceil(bbox.x2 - x1) + padding;
  const height = Math.ceil(bbox.y2 - y1) + padding;
  const viewBox = `${x1} ${y1} ${width} ${height}`;

  // Also generate per-glyph paths for staggered animation
  const glyphPaths = [];
  let xCursor = X_OFFSET;
  for (let i = 0; i < TEXT.length; i++) {
    const glyph = font.charToGlyph(TEXT[i]);
    const glyphPath = glyph.getPath(xCursor, Y_OFFSET, FONT_SIZE);
    const glyphD = glyphPath.toPathData(2);
    if (glyphD && glyphD.trim().length > 0) {
      const gb = glyphPath.getBoundingBox();
      glyphPaths.push({
        char: TEXT[i],
        d: glyphD,
        x: Math.floor(gb.x1),
        y: Math.floor(gb.y1),
        w: Math.ceil(gb.x2) - Math.floor(gb.x1),
        h: Math.ceil(gb.y2) - Math.floor(gb.y1),
      });
    }
    const advance = glyph.advanceWidth * (FONT_SIZE / font.unitsPerEm);

    // Apply kerning
    if (i < TEXT.length - 1) {
      const nextGlyph = font.charToGlyph(TEXT[i + 1]);
      const kerning = font.getKerningValue(glyph, nextGlyph);
      xCursor += advance + kerning * (FONT_SIZE / font.unitsPerEm);
    } else {
      xCursor += advance;
    }
  }

  const output = `// Auto-generated by scripts/generate-name-svg.mjs — do not edit manually
export const HERO_NAME_VIEWBOX = "${viewBox}";
export const HERO_NAME_WIDTH = ${width};
export const HERO_NAME_HEIGHT = ${height};

/** Full combined path for "Cormac Lee" */
export const HERO_NAME_PATH = "${d}";

/** Per-glyph paths for staggered animation */
export const HERO_NAME_GLYPHS: { char: string; d: string; x: number; y: number; w: number; h: number }[] = ${JSON.stringify(glyphPaths, null, 2)};
`;

  const outPath = resolve(__dirname, "../components/ui/hero-name-paths.ts");
  writeFileSync(outPath, output, "utf-8");
  console.log(`Wrote ${outPath}`);
  console.log(`viewBox: ${viewBox}`);
  console.log(`Glyphs: ${glyphPaths.length}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
